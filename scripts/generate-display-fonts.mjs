import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createHash } from 'node:crypto';

// Run explicitly against the GFX library already used for firmware compilation.
// The generated module keeps browsers and devices on identical bitmap glyphs.
const root = fileURLToPath(new URL('..', import.meta.url));
const library = process.argv[2];
if (!library) throw new Error('Pass the installed Adafruit_GFX_Library directory');
const sources = [
  ...['FreeSans9pt7b', 'FreeSansBold9pt7b', 'FreeSansBold18pt7b', 'FreeSans12pt7b', 'FreeSansBold12pt7b'].map(name => ({ name, directory: path.join(library, 'Fonts') })),
  ...['SourceSans3Regular9pt7b', 'SourceSans3Bold9pt7b', 'SourceSans3Bold18pt7b', 'SourceSans3Regular12pt7b', 'SourceSans3Bold12pt7b'].map(name => ({ name, directory: path.join(root, 'firmware/focusdesk_device/fonts') })),
  ...['NunitoRegular10px', 'NunitoBold10px', 'NunitoRegular11px', 'NunitoBold11px', 'NunitoRegular13px', 'NunitoRegular16px', 'NunitoBold16px', 'NunitoBold17px'].map(name => ({ name, directory: path.join(root, 'firmware/focusdesk_device/fonts') })),
];
const fonts = [];
for (const { name, directory } of sources) {
  const source = await readFile(path.join(directory, `${name}.h`), 'utf8');
  const bitmapSource = source.match(/Bitmaps\[\][^{]*\{([\s\S]*?)\};/)[1];
  const bitmap = [...bitmapSource.matchAll(/0x[\da-f]+/gi)].map(item => Number(item[0]));
  const glyphSource = source.match(/Glyphs\[\][^{]*\{([\s\S]*?)\};/)[1];
  const glyphs = [...glyphSource.matchAll(/\{\s*([\d,\s-]+)\}/g)].map(item => item[1].split(',').map(Number));
  if (glyphs.length !== 95 || !bitmap.length) throw new Error(`Unexpected font format ${name}`);
  fonts.push({ name, sha256: createHash('sha256').update(source).digest('hex'), bitmap, glyphs });
}
const license = await readFile(path.join(library, 'license.txt'), 'utf8');
await writeFile(path.join(root, 'contracts/display-fonts.ts'),
  `/** Generated by scripts/generate-display-fonts.mjs from GFX bitmap headers.\n` +
  ` * Nunito originates from Google Fonts, SIL OFL 1.1.\n` +
  ` * Source Sans 3 originates from Adobe, SIL OFL 1.1.\n` +
  ` * Legacy FreeSans originates from GNU FreeFont, GPL-3.0-or-later with font embedding exception.\n` +
  ` * Full font notices and license texts are in contracts/DISPLAY_FONT_LICENSE.txt.\n` +
  license.split('\n').map(line => ` * ${line}`).join('\n') +
  `\n */\nexport const DISPLAY_FONTS = ${JSON.stringify(fonts)};\n`);
